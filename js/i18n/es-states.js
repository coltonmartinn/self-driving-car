// ages, months and hours, the way StateQuiz writes them
(() => {
   const entries = {};
   for (let years = 14; years <= 17; years++) {
      entries[years + " years old"] = years + " años";
      for (const months of [3, 6, 9]) {
         entries[years + " years, " + months + " months old"] = years + " años y " + months + " meses";
      }
   }
   for (const months of [3, 6, 9, 12]) {
      entries[months + " months"] = months + " meses";
   }
   for (const hours of [20, 30, 40, 45, 50, 60, 65, 70, 100]) {
      entries[hours + " hours"] = hours + " horas";
      for (const night of [2, 6, 10, 15]) {
         entries[hours + " hours, " + night + " of them at night"] = hours + " horas, " + night + " de ellas de noche";
      }
   }
   I18N.add("es", entries);
})();
